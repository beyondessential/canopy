// Generate the safety-mode grade map the interface reads, from the OpenAPI
// document the server emits.
//
// Spec: `.workhorse/specs/private-server/safety-modes.md` (id `SAFE`).
//
// The grade is declared once, on each handler's `routes!` entry, and travels
// here as the `x-canopy-safety-mode` operation extension. `openapi-typescript`
// does not surface `x-` extensions, and a component choosing how to present a
// control needs a runtime value anyway — `callApi(module, fn)` is a runtime
// pair — so the map is generated as data rather than as a type.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const EXTENSION = "x-canopy-safety-mode";
const MODES = new Set(["read-only", "write", "danger"]);

const document = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"));

const grades = new Map();
for (const [path, item] of Object.entries(document.paths ?? {})) {
	for (const operation of Object.values(item)) {
		if (typeof operation !== "object" || operation === null) continue;
		const mode = operation[EXTENSION];
		if (mode === undefined) continue;
		if (!MODES.has(mode)) {
			throw new Error(`${path} declares an unknown safety mode: ${mode}`);
		}
		// `callApi` addresses an endpoint as a (module, fn) pair under `/api/`,
		// so that is the key: `admins/add`, `fleet/applications/list`.
		const key = path.replace(/^\/api\//, "");
		grades.set(key, mode);
	}
}

const entries = [...grades].sort(([a], [b]) => a.localeCompare(b));

const body = `// @generated by scripts/gen-safety-modes.mjs from openapi.json — do not edit.
//
// The safety mode each endpoint on the administrative surface requires (see the
// SAFE spec). Declared once on the handler's \`routes!\` entry in the Rust
// source; regenerated by \`just gen-openapi\`.

import type { SafetyMode } from "./safety";

/** The mode each endpoint requires, keyed as \`module/fn\`. */
export const SAFETY_MODES = {
${entries.map(([key, mode]) => `\t"${key}": "${mode}",`).join("\n")}
} as const satisfies Record<string, SafetyMode>;

/**
 * An endpoint on the administrative surface, named the way a control names the
 * endpoint it calls. A misspelt name is a type error rather than a control that
 * quietly reads as needing no mode at all.
 */
export type GradedEndpoint = keyof typeof SAFETY_MODES;
`;

writeFileSync(join(root, "src/safety-modes.ts"), body);
console.log(`safety modes: ${entries.length} endpoints graded`);
